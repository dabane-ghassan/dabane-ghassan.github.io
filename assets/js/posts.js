/* Blog helpers shared by the home page, blog index and post page.
   Posts are Markdown files in /posts, listed in /posts/index.json
   (generated by scripts/build.mjs — run automatically by GitHub Actions). */
(function () {
  'use strict';

  var Posts = {};
  var PRIV = '\uE000'; // private-use char: survives Markdown parsing untouched

  /* ---------------- data ---------------- */
  var cache = null;
  Posts.load = function () {
    if (!cache) {
      cache = fetch('posts/index.json', { cache: 'no-cache' })
        .then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
        .then(function (j) { return (j.posts || j || []).filter(function (p) { return !p.draft; }); })
        .catch(function () { return []; });
    }
    return cache;
  };

  /* One entry per article: if an article exists in several languages (same `ref`),
     keep the version in the reader’s language. */
  Posts.forLang = function (posts, lang) {
    var groups = {}, order = [];
    posts.forEach(function (p) {
      var k = p.ref || p.slug;
      if (!groups[k]) { groups[k] = []; order.push(k); }
      groups[k].push(p);
    });
    return order.map(function (k) {
      var g = groups[k];
      return g.filter(function (p) { return p.lang === lang; })[0] || g[0];
    }).sort(function (a, b) { return a.date < b.date ? 1 : a.date > b.date ? -1 : 0; });
  };

  Posts.translation = function (posts, post) {
    if (!post || !post.ref) return null;
    return posts.filter(function (p) { return p.ref === post.ref && p.slug !== post.slug; })[0] || null;
  };

  Posts.fmtDate = function (iso, lang, long) {
    if (!iso) return '';
    var d = new Date(iso + (iso.length === 10 ? 'T00:00:00Z' : ''));
    if (isNaN(d)) return iso;
    return new Intl.DateTimeFormat(lang === 'fr' ? 'fr-FR' : 'en-GB',
      { day: 'numeric', month: long ? 'long' : 'short', year: 'numeric', timeZone: 'UTC' }).format(d);
  };

  Posts.esc = function (s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  };

  Posts.itemHTML = function (p, lang) {
    var e = Posts.esc;
    var badge = p.lang && p.lang !== lang ? '<span class="lang-badge">' + e(p.lang) + '</span>' : '';
    return '<li><a href="post.html?p=' + encodeURIComponent(p.slug) + '">' +
      '<span class="date mono">' + Posts.fmtDate(p.date, lang) + '</span>' +
      '<span><span class="title">' + e(p.title) + '</span></span>' +
      '<span class="side">' + badge + '<span class="arrow" aria-hidden="true">→</span></span>' +
      '</a></li>';
  };

  /* ---------------- presentations ---------------- */
  var talks = null;
  Posts.loadTalks = function () {
    if (!talks) {
      talks = fetch('presentations/index.json', { cache: 'no-cache' })
        .then(function (r) { if (!r.ok) throw new Error(r.status); return r.json(); })
        .then(function (j) { return j.talks || []; })
        .catch(function () { return []; });
    }
    return talks;
  };
  Posts.talkHTML = function (t, lang) {
    var e = Posts.esc;
    var badge = t.lang && t.lang !== lang ? '<span class="lang-badge">' + e(t.lang) + '</span>' : '';
    return '<li><a href="presentations/' + t.file.split('/').map(encodeURIComponent).join('/') + '" target="_blank" rel="noopener">' +
      '<span class="date mono">' + (t.date ? Posts.fmtDate(t.date, lang) : '') + '</span>' +
      '<span><span class="title">' + e(t.title) + '</span>' + (t.event ? '<span class="sub">' + e(t.event) + '</span>' : '') + '</span>' +
      '<span class="side">' + badge + '<span class="arrow" aria-hidden="true">↗</span></span>' +
      '</a></li>';
  };

  /* ---------------- front matter (tiny YAML subset) ---------------- */
  function scalar(v) {
    v = v.trim();
    if (/^(['"]).*\1$/.test(v)) return v.slice(1, -1);
    v = v.replace(/\s+#.*$/, '');
    if (/^\[.*\]$/.test(v)) return v.slice(1, -1).split(',').map(scalar).filter(function (x) { return x !== ''; });
    if (v === 'true') return true;
    if (v === 'false') return false;
    return v;
  }
  Posts.frontMatter = function (src) {
    src = src.replace(/^\uFEFF/, '');
    var m = /^---[ \t]*\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/.exec(src);
    if (!m) return { data: {}, body: src };
    var data = {}, key = null;
    m[1].split(/\r?\n/).forEach(function (line) {
      if (!line.trim() || /^\s*#/.test(line)) return;
      var li = /^\s*-\s+(.*)$/.exec(line);
      if (li && key) { if (!Array.isArray(data[key])) data[key] = []; data[key].push(scalar(li[1])); return; }
      var kv = /^([A-Za-z0-9_-]+)\s*:\s*(.*)$/.exec(line);
      if (kv) { key = kv[1]; data[key] = kv[2].trim() === '' ? '' : scalar(kv[2]); }
    });
    return { data: data, body: src.slice(m[0].length) };
  };

  /* ---------------- Markdown + LaTeX ---------------- */
  function tok(kind, i) { return PRIV + kind + i + PRIV; }

  function katexHTML(tex, display) {
    try {
      return window.katex.renderToString(tex, { displayMode: display, throwOnError: false, output: 'html', strict: 'ignore', trust: false });
    } catch (e) {
      return '<code class="math-error">' + Posts.esc(tex) + '</code>';
    }
  }

  Posts.render = function (md) {
    var code = [], math = [], notes = {}, noteOrder = [];

    // 1. protect code (fenced, then inline) so $ and [^x] inside code are left alone
    md = md.replace(/(^|\n)(`{3,}|~{3,})[^\n]*\n[\s\S]*?\n\2[ \t]*(?=\n|$)/g, function (m) { code.push(m); return tok('C', code.length - 1); });
    md = md.replace(/(`+)([^`\n][\s\S]*?)\1(?!`)/g, function (m) { code.push(m); return tok('C', code.length - 1); });

    // 2. math: \$ is a literal dollar
    md = md.replace(/\\\$/g, tok('D', 0));
    function addMath(tex, display) { math.push({ tex: tex, display: display }); return tok(display ? 'B' : 'M', math.length - 1); }
    md = md.replace(/\$\$([\s\S]+?)\$\$/g, function (_, t) { return addMath(t, true); });
    md = md.replace(/\\\[([\s\S]+?)\\\]/g, function (_, t) { return addMath(t, true); });
    md = md.replace(/\\\(([\s\S]+?)\\\)/g, function (_, t) { return addMath(t, false); });
    md = md.replace(/\$([^\s$](?:[^$\n]*?[^\s$\\])?)\$(?!\d)/g, function (_, t) { return addMath(t, false); });

    // 3. footnotes: [^id] references and "[^id]: text" definitions
    md = md.replace(/^\[\^([^\]\s]+)\]:[ \t]+(.+(?:\n(?:[ ]{2,}|\t).+)*)/gm, function (_, id, text) {
      notes[id] = text.replace(/\n\s+/g, ' '); return '';
    });
    md = md.replace(/\[\^([^\]\s]+)\]/g, function (m, id) {
      if (!(id in notes)) return m;
      var n = noteOrder.indexOf(id);
      if (n < 0) { noteOrder.push(id); n = noteOrder.length - 1; }
      var sid = Posts.esc(id);
      return '<sup class="fn" id="fnref-' + sid + '"><a href="#fn-' + sid + '">' + (n + 1) + '</a></sup>';
    });

    // 4. restore code, parse Markdown
    md = md.replace(new RegExp(PRIV + 'C(\\d+)' + PRIV, 'g'), function (_, i) { return code[+i]; });
    var html = window.marked.parse(md, { gfm: true, breaks: false });

    if (noteOrder.length) {
      html += '<section class="footnotes" aria-label="Notes"><ol>' + noteOrder.map(function (id) {
        var sid = Posts.esc(id);
        return '<li id="fn-' + sid + '">' + window.marked.parseInline(notes[id]) + ' <a class="fn-back" href="#fnref-' + sid + '" aria-label="Back">↩</a></li>';
      }).join('') + '</ol></section>';
    }

    // 5. put rendered math back
    html = html.replace(new RegExp('<p>\\s*' + PRIV + 'B(\\d+)' + PRIV + '\\s*</p>', 'g'), function (_, i) {
      return '<div class="math-display">' + katexHTML(math[+i].tex, true) + '</div>';
    });
    html = html.replace(new RegExp(PRIV + '([BM])(\\d+)' + PRIV, 'g'), function (_, k, i) {
      var h = katexHTML(math[+i].tex, k === 'B');
      return k === 'B' ? '<span class="math-display" style="display:block">' + h + '</span>' : h;
    });
    html = html.replace(new RegExp(PRIV + 'D0' + PRIV, 'g'), '$');
    return html;
  };

  Posts.readingTime = function (text) {
    var words = (text.replace(/```[\s\S]*?```/g, '').match(/\S+/g) || []).length;
    return Math.max(1, Math.round(words / 220));
  };

  window.Posts = Posts;
})();
